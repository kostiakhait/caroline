"""turn.background.relay.worth -- a microagent that decides whether one piece
of text, generated by Caroline's (the Camerlengo-backed AI assistant's) own
headless background/reminder-chore session, is actually worth relaying into
the user's PRIMARY chat as a standalone, unprompted message.

Per explicit instruction (2026-10-14): Caroline's background session (vault
backups, mailbox sweeps, messenger polling, etc.) runs with no chat window of
its own -- whatever it has left to say once a cycle genuinely ends gets
spliced directly into the user's own primary conversation via
deliver_relayed_reply, with no question asked and no surrounding context
beyond the message itself. reply.review (ReplyReview.py) already filters
internal-mechanics leaks and off-task/robotic phrasing, but it has no opinion
on NEWSWORTHINESS -- a perfectly clean, human-sounding, on-task sentence like
"No new messages in Telegram, vault note refreshed" passes all three of its
rules untouched and still isn't something worth interrupting the user's own
chat with. Confirmed live the same day: three of four real relayed messages
in one morning were exactly this kind of routine "nothing happened" status
noise (a Telegram check, an in-progress mailbox cleanup, a backup
confirmation) leaking through because nothing downstream of review_reply ever
asked "is this worth the interruption" as its own, separate question. This
agent is that separate question -- registered into the same shared Runtime
as ReplyReview/PermissionGuard/RefusalGuard/ReplyExpected, its own command
(`reply:backgroundRelayWorth`), its own billing label.

Bug fix (2026-10-15), confirmed live: judging TEXT in total isolation missed
a real case -- a session that delegated a mailbox sweep to its own sub-agent
and reported "I'll do the backup myself" was judged worth relaying (it reads
as a real decision), when it was actually just plan/process description with
no result yet. Takes an optional `task` (the reminder's own note, or the
sub-agent's own brief) so TEXT can be judged AGAINST what was actually asked,
not merely on its own tone -- see prompt_worth's own comment for the rule.
"""

from __future__ import annotations

from typing import Any, List, Optional

from app.microagent_client import Microagent as M

WORTH = "turn.background.relay.worth"

_STRING = {"type": "string"}


def _object(properties: dict, required: Optional[List[str]] = None) -> dict:
    return {"type": "object", "properties": properties, "required": list(properties) if required is None else required}


# Evolution-engine genome (2026-10-17): see PermissionGuard.py's own
# GUARD_RULES_TEXT comment for the split's rationale. One wrinkle here:
# the per-call `task_clause` is inserted in the MIDDLE of the rules, not
# appended after them -- `{{TASK_CLAUSE}}` is a literal placeholder token
# (never `.format()`-style interpolation, so a literal `{`/`}` anywhere
# else in a mutated genome can never be mistaken for one), resolved by a
# plain string .replace() in prompt_worth below. A mutator working on this
# genome must preserve the token verbatim if present (wherever it ends up
# making sense in its own rewrite) -- it is never itself part of what gets
# judged.
WORTH_RULES_TEXT = (
    "An AI assistant runs small periodic background chores and sub-agents on its own initiative -- checking "
    "a mailbox, polling a messenger account for new messages, refreshing a memory/vault backup note, a "
    "delegated sub-agent task, and similar -- inside a SEPARATE, headless session with no chat window of "
    "its own. When such a chore's cycle finishes, whatever it has left to say gets delivered as a "
    "STANDALONE, UNPROMPTED message spliced directly into the user's own primary chat -- interrupting "
    "whatever else is going on there, with no question asked and no context given beyond the message "
    "itself.\n\n"
    "Decide: is the TEXT below worth that interruption right now, or is it routine status noise the user "
    "does not need pushed at them unasked?\n\n"
    "{{TASK_CLAUSE}}"
    "WHEN A TASK IS GIVEN, JUDGE TEXT AGAINST IT, not in isolation: a result that merely confirms the task "
    "was carried out exactly as asked, with nothing unexpected, is NOT worth relaying -- even if it sounds "
    "substantial or the task itself sounded important ('delegated the mailbox sweep to a sub-agent and will "
    "do the backup myself' is a plan, not news, even though it mentions real work). A result that DIVERGES "
    "from what the task would predict -- a problem found, something expected not found, a decision now "
    "needed from the user, new information the task didn't already imply -- is worth relaying.\n\n"
    "NOT worth relaying (worth_relaying: false) -- routine, expected, no actual news:\n"
    "- \"nothing new\", \"no new messages\", \"still in progress\", \"still running\", \"will keep checking\"\n"
    "- a chore reporting it simply did what it was always going to do, with no surprise or problem (a "
    "backup/note update completing normally, a routine check finding nothing worth flagging)\n"
    "- a meta-remark about the assistant's own standing intentions (\"I won't send anything without "
    "explicit permission\", \"staying available\") with no concrete news attached\n"
    "- a description of its OWN plan/delegation/process (what it decided to do, or who it handed work to) "
    "when that plan hasn't produced an actual result yet\n\n"
    "Worth relaying (worth_relaying: true) -- an actual, standalone-worthy finding:\n"
    "- a genuine discovery, problem, anomaly, or decision point the user would plausibly want to know "
    "about on its own merits, independent of having asked for an update\n"
    "- something that plausibly needs the user's attention or action\n"
    "- new substantive information, even if phrased calmly or briefly\n\n"
    "Judge TEXT purely on whether IT ITSELF would be worth sending as a cold, unprompted message with no "
    "other context -- not on how politely or fluently it is worded. A calmly-phrased real finding is "
    "still worth relaying; an elaborately-worded non-event is still not. TEXT may be written in any "
    "language -- judge its content, not its language.\n\n"
)


def _task_clause(input: Any) -> str:
    task = (input.get("task") or "").strip()
    return (
        f"TASK this was actually about (the reminder's own note, or the sub-agent's own brief):\n{task}\n\n"
        if task else ""
    )


def _data_section(input: Any) -> str:
    return f"TEXT:\n{input['text']}"


def prompt_worth(input: Any, context: Any) -> str:
    rules = WORTH_RULES_TEXT.replace("{{TASK_CLAUSE}}", _task_clause(input))
    return rules + _data_section(input)


def verify_worth(input: Any, output: Any) -> Optional[str]:
    if not isinstance(output.get("worth_relaying"), bool):
        return '"worth_relaying" must be a boolean'
    return None


def llm_agents() -> List[M.Agent]:
    return [
        M.Agent(
            WORTH, "1",
            "Decides whether one piece of text from Caroline's own background/reminder-chore session is a "
            "genuine standalone finding worth interrupting the user's primary chat with, versus routine "
            "'nothing happened' status noise -- judged against the task it was actually given, when known.",
            input_schema=_object({"task": _STRING, "text": _STRING}, required=["text"]),
            output_schema=_object({"worth_relaying": {"type": "boolean"}, "reason": _STRING}, required=["worth_relaying", "reason"]),
            build_prompt=prompt_worth, verify=verify_worth,
        ),
    ]
